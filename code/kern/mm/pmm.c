// virtual address of physical page array
struct Page *pages;
// amount of physical memory (in pages)
size_t npage = 0;
// The kernel image is mapped at VA=KERNBASE and PA=info.base
uint_t va_pa_offset;
// memory starts at 0x80000000 in RISC-V
const size_t nbase = DRAM_BASE / PGSIZE;

// virtual address of boot-time page directory
pde_t *boot_pgdir_va = NULL;
// physical address of boot-time page directory
uintptr_t boot_pgdir_pa;

// physical memory management
const struct pmm_manager *pmm_manager;

static void check_alloc_page(void);
static void check_pgdir(void);
static void check_boot_pgdir(void);

// init_pmm_manager - initialize a pmm_manager instance
static void init_pmm_manager(void)
{
    pmm_manager = &default_pmm_manager;
    cprintf("memory management: %s\n", pmm_manager->name);
    pmm_manager->init();
}

// init_memmap - call pmm->init_memmap to build Page struct for free memory
static void init_memmap(struct Page *base, size_t n)
{
    pmm_manager->init_memmap(base, n);
}

// alloc_pages - call pmm->alloc_pages to allocate a continuous n*PAGESIZE
// memory
struct Page *alloc_pages(size_t n)
{
    struct Page *page = NULL;
    bool intr_flag;
    local_intr_save(intr_flag);
    {
        page = pmm_manager->alloc_pages(n);
    }
    local_intr_restore(intr_flag);
    return page;
}

// free_pages - call pmm->free_pages to free a continuous n*PAGESIZE memory
void free_pages(struct Page *base, size_t n)
{
    bool intr_flag;
    local_intr_save(intr_flag);
    {
        pmm_manager->free_pages(base, n);
    }
    local_intr_restore(intr_flag);
}

// nr_free_pages - call pmm->nr_free_pages to get the size (nr*PAGESIZE)
// of current free memory
size_t nr_free_pages(void)
{
    size_t ret;
    bool intr_flag;
    local_intr_save(intr_flag);
    {
        ret = pmm_manager->nr_free_pages();
    }
    local_intr_restore(intr_flag);
    return ret;
}

// lab2: 初始化从设备树探测到的物理页。
/* page_init - 根据设备树提供的物理内存信息建立物理页描述符布局，
 * 将排除 OpenSBI、内核镜像和页描述符数组占用后的完整空闲页交给 pmm_manager */
static void page_init(void) {
    uint64_t mem_base = get_memory_base();
    uint64_t mem_size = get_memory_size();

    // 设备树信息无效时终止初始化
    if (mem_base == 0 || mem_size == 0) {
        panic("page_init: invalid physical memory info from device tree");
    }

    // 设置虚实映射偏移量（va = pa + offset）
    va_pa_offset = PHYSICAL_MEMORY_OFFSET;

    // 物理内存总页数 = 物理内存结束地址对应的页号
    npage = PPN(mem_base + mem_size);

    // 页描述符数组起始地址：内核镜像 end 之后按页对齐
    extern char end[];
    pages = (struct Page *)ROUNDUP((uintptr_t)end, PGSIZE);

    // 输出探测到的物理内存范围
    cprintf("physical memory: base=0x%016lx, size=0x%016lx (%lu MB)\n",
            mem_base, mem_size, (unsigned long)(mem_size / (1024 * 1024)));
    cprintf("npage = %lu, nbase = %lu, pages (va) = 0x%016lx\n",
            (unsigned long)npage, (unsigned long)nbase, (uintptr_t)pages);

    // 将所有物理页描述符初始化为 reserved（不可分配）
    size_t i;
    for (i = 0; i < npage - nbase; i++) {
        SetPageReserved(&pages[i]);
    }

    // 可用物理内存起始地址：页描述符数组结束之后按页对齐
    uintptr_t freemem_pa = ROUNDUP(
        PADDR((uintptr_t)pages + (npage - nbase) * sizeof(struct Page)), PGSIZE);
    size_t nr_free = (size_t)((mem_base + mem_size - freemem_pa) / PGSIZE);

    cprintf("free memory: 0x%016lx ~ 0x%016lx, %lu pages\n",
            freemem_pa, mem_base + mem_size, (unsigned long)nr_free);

    // 存在完整空闲页时才注册到 pmm_manager
    if (nr_free > 0) {
        init_memmap(pa2page(freemem_pa), nr_free);
    }
}

static void enable_paging(void)
{
    write_csr(satp, 0x8000000000000000 | (boot_pgdir_pa >> RISCV_PGSHIFT));
}

// boot_map_segment - setup&enable the paging mechanism
// parameters
//  la:   linear address of this memory need to map (after x86 segment map)
//  size: memory size
//  pa:   physical address of this memory
//  perm: permission of this memory
static void boot_map_segment(pde_t *pgdir, uintptr_t la, size_t size,
                             uintptr_t pa, uint32_t perm)
{
    assert(PGOFF(la) == PGOFF(pa));
    size_t n = ROUNDUP(size + PGOFF(la), PGSIZE) / PGSIZE;
    la = ROUNDDOWN(la, PGSIZE);
    pa = ROUNDDOWN(pa, PGSIZE);
    for (; n > 0; n--, la += PGSIZE, pa += PGSIZE)
    {
        pte_t *ptep = get_pte(pgdir, la, 1);
        assert(ptep != NULL);
        *ptep = pte_create(pa >> PGSHIFT, PTE_V | perm);
    }
}

// boot_alloc_page - allocate one page using pmm->alloc_pages(1)
// return value: the kernel virtual address of this allocated page
// note: this function is used to get the memory for PDT(Page Directory
// Table)&PT(Page Table)
static void *boot_alloc_page(void)
{
    struct Page *p = alloc_page();
    if (p == NULL)
    {
        panic("boot_alloc_page failed.\n");
    }
    return page2kva(p);
}

// pmm_init - setup a pmm to manage physical memory, build PDT&PT to setup
// paging mechanism
//         - check the correctness of pmm & paging mechanism, print PDT&PT
void pmm_init(void)
{
    // We need to alloc/free the physical memory (granularity is 4KB or other
    // size).
    // So a framework of physical memory manager (struct pmm_manager)is defined
    // in pmm.h
    // First we should init a physical memory manager(pmm) based on the
    // framework.
    // Then pmm can alloc/free the physical memory.
    // Now the first_fit/best_fit/worst_fit/buddy_system pmm are available.
    init_pmm_manager();

    // detect physical memory space, reserve already used memory,
    // then use pmm->init_memmap to create free page list
    page_init();

    // use pmm->check to verify the correctness of the alloc/free function in a
    // pmm
    check_alloc_page();
    // create boot_pgdir, an initial page directory(Page Directory Table, PDT)
    extern char boot_page_table_sv39[];
    boot_pgdir_va = (pte_t *)boot_page_table_sv39;
    boot_pgdir_pa = PADDR(boot_pgdir_va);

    check_pgdir();

    static_assert(KERNBASE % PTSIZE == 0 && KERNTOP % PTSIZE == 0);

    // now the basic virtual memory map(see memalyout.h) is established.
    // check the correctness of the basic virtual memory map.
    check_boot_pgdir();

    kmalloc_init();
}

// get_pte - get pte and return the kernel virtual address of this pte for la
//        - if the PT contians this pte didn't exist, alloc a page for PT
// parameter:
//  pgdir:  the kernel virtual base address of PDT
//  la:     the linear address need to map
//  create: a logical value to decide if alloc a page for PT
// return vaule: the kernel virtual address of this pte
pte_t *get_pte(pde_t *pgdir, uintptr_t la, bool create)
{
    pde_t *pdep1 = &pgdir[PDX1(la)];
    struct Page *new_directory = NULL;
    if (!(*pdep1 & PTE_V))
    {
        if (!create || (new_directory = alloc_page()) == NULL)
        {
            return NULL;
        }
        set_page_ref(new_directory, 1);
        memset(page2kva(new_directory), 0, PGSIZE);
    }

    // A valid RWX entry at an upper level already maps a superpage.
    else if (*pdep1 & (PTE_R | PTE_W | PTE_X))
    {
        return NULL;
    }
    pde_t *directory = new_directory != NULL ? page2kva(new_directory)
                                            : KADDR(PDE_ADDR(*pdep1));
    pde_t *pdep0 = &directory[PDX0(la)];
    if (!(*pdep0 & PTE_V))
    {
        struct Page *page;
        if (!create || (page = alloc_page()) == NULL)
        {
            if (new_directory != NULL)
            {
                set_page_ref(new_directory, 0);
                free_page(new_directory);
            }
            return NULL;
        }
        set_page_ref(page, 1);
        memset(page2kva(page), 0, PGSIZE);
        *pdep0 = ptd_create(page2ppn(page));
    }
    else if (*pdep0 & (PTE_R | PTE_W | PTE_X))
    {
        return NULL;
    }
    if (new_directory != NULL)
    {
        *pdep1 = ptd_create(page2ppn(new_directory));
    }
    return &((pte_t *)KADDR(PDE_ADDR(*pdep0)))[PTX(la)];
}

// get_page - get related Page struct for linear address la using PDT pgdir
struct Page *get_page(pde_t *pgdir, uintptr_t la, pte_t **ptep_store)
{
    pte_t *ptep = get_pte(pgdir, la, 0);
    if (ptep_store != NULL)
    {
        *ptep_store = ptep;
    }
    if (ptep != NULL && *ptep & PTE_V)
    {
        return pte2page(*ptep);
    }
    return NULL;
}

//LAB4 function1 YOUR CODE
static void
page_remove_pte(pde_t *pgdir, uintptr_t la, pte_t *ptep)
{
    if (!(*ptep & PTE_V))
    {
        return;
    }

    struct Page *page = pte2page(*ptep);
    *ptep = 0;
    tlb_invalidate(pgdir, la);
    if (page_ref_dec(page) == 0)
    {
        free_page(page);
    }
}

void
page_remove(pde_t *pgdir, uintptr_t la)
{
    pte_t *ptep = get_pte(pgdir, la, 0);
    if (ptep != NULL)
    {
        page_remove_pte(pgdir, la, ptep);
    }
}

int
page_insert(pde_t *pgdir, struct Page *page, uintptr_t la, uint32_t perm)
{
    pte_t *ptep = get_pte(pgdir, la, 1);
    if (ptep == NULL)
    {
        return -E_NO_MEM;
    }

    // Changing the permissions of an existing mapping keeps its reference.
    if (!(*ptep & PTE_V) || pte2page(*ptep) != page)
    {
        page_ref_inc(page);
        page_remove_pte(pgdir, la, ptep);
    }
    // Sv39 needs R or X in a leaf and requires R whenever W is set.
    if ((perm & (PTE_R | PTE_X)) == 0 || (perm & PTE_W))
    {
        perm |= PTE_R;
    }
    *ptep = pte_create(page2ppn(page), perm);
    tlb_invalidate(pgdir, la);
    return 0;
}

// invalidate a TLB entry, but only if the page tables being
// edited are the ones currently in use by the processor.
void tlb_invalidate(pde_t *pgdir, uintptr_t la)
{
    // flush_tlb();
    // The flush_tlb flush the entire TLB, is there any better way?
    asm volatile("sfence.vma %0" : : "r"(la) : "memory");
}

